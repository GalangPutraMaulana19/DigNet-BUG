      <p><strong>Latar Belakang:</strong></p>
      <p>IndiHome merupakan layanan triple play dari PT Telkom Indonesia yang memadukan akses internet berbasis fiber to the home (FTTH), layanan digital melalui perangkat set-top box (STB), dan telepon. Di wilayah Witel Bekasi, instalasi dilaksanakan melalui kerja sama Telkom Akses dengan mitra pelaksana seperti PT Mutiara Sentosa.</p>
      
      <p><strong>Permasalahan:</strong></p>
      <p>Dalam praktik, masih dijumpai variasi hasil instalasi dan proses diagnosis yang bergantung pada pengalaman individu teknisi. Hal ini menyebabkan mean time to repair memanjang dan frekuensi kunjungan ulang meningkat selama masa retensi 60 hari.</p>
      
      <p><strong>Solusi:</strong></p>
      <p>Sistem pakar berbasis aturan IF-THEN dengan metode Forward Chaining dan Certainty Factor untuk mendiagnosis gangguan pada komponen IndiHome (ODP, ONT, STB, Telepon). Sistem ini dirancang sebagai alat bantu bagi teknisi provisioning agar langkah diagnosis lebih seragam, waktu pemulihan lebih singkat, dan kepuasan pelanggan terjaga.</p>
      
      <p><strong>Metode:</strong></p>
      <ul style="text-align: left; padding-left: 30px;">
        <li>Forward Chaining: Inferensi dari gejala menuju diagnosis</li>
        <li>Certainty Factor: Menangani ketidakpastian dengan nilai -1 hingga +1</li>
        <li>Basis pengetahuan dari teknisi assurance dan studi literatur</li>
      </ul>
