    <script>
    function kirimContactForm() {
        const reg = /^[A-Z0-9._%+-]+@([A-Z0-9-]+\.)+[A-Z]{2,4}$/i;
        const nama = document.getElementById('masukkanNama').value;
        const email = document.getElementById('masukkanEmail').value;
        const pesan = document.getElementById('masukkanPesan').value;
        const statusMsg = document.querySelector('.statusMsg');
        
        // Validation
        if(nama.trim() === '') {
            alert('Masukkan nama Anda.');
            document.getElementById('masukkanNama').focus();
            return false;
        }
        if(email.trim() === '') {
            alert('Masukkan email Anda.');
            document.getElementById('masukkanEmail').focus();
            return false;
        }
        if(email.trim() !== '' && !reg.test(email)) {
            alert('Masukkan email yang valid.');
            document.getElementById('masukkanEmail').focus();
            return false;
        }
        if(pesan.trim() === '') {
            alert('Masukkan pesan Anda.');
            document.getElementById('masukkanPesan').focus();
            return false;
        }
        
        // Send via Fetch API (modern replacement for $.ajax)
        const formData = new FormData();
        formData.append('contactFrmSubmit', '1');
        formData.append('nama', nama);
        formData.append('email', email);
        formData.append('pesan', pesan);
        
        const modalBody = document.querySelector('#modalForm .modal-body');
        const submitBtn = document.querySelector('#modalForm .btn-primary');
        
        submitBtn.disabled = true;
        modalBody.style.opacity = '0.5';
        
        fetch('kirim_form.php', {
            method: 'POST',
            body: formData
        })
        .then(response => response.text())
        .then(data => {
            if(data.trim() === 'ok') {
                document.getElementById('masukkanNama').value = '';
                document.getElementById('masukkanEmail').value = '';
                document.getElementById('masukkanPesan').value = '';
                statusMsg.innerHTML = '<span class="text-success">Terima kasih telah menghubungi kami.</span>';
            } else {
                statusMsg.innerHTML = '<span class="text-danger">Ada sedikit masalah, silakan coba lagi.</span>';
            }
            submitBtn.disabled = false;
            modalBody.style.opacity = '1';
        })
        .catch(error => {
            statusMsg.innerHTML = '<span class="text-danger">Error: ' + error.message + '</span>';
            submitBtn.disabled = false;
            modalBody.style.opacity = '1';
        });
    }
    </script>
